// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures (radar-2):
//
//   base       = tvl_usd x BASE_MULTIPLE (0.25)
//   growthMult = 1 + clamp(change_7d, -50, 100) / 100 x 0.5   (a 4448% week is capped, not believed)
//   ageMult    = 0.70 rising to 1.00 at 90-540 days, fading to 0.75 past 3y, 0.85 if age unknown
//                (a token is most likely while a protocol is proven but still pre-token; a
//                5-year-old protocol with no token is less likely to launch one tomorrow)
//   farmMult   = by category only, never by name: 1.00 farmable (Lending, Dexs, Yield, Liquid
//                Staking, Restaking, Derivatives, CDP, RWA, Insurance, ...), 0.85 curator /
//                allocator / staking-pool, 0.70 chain / payments, 0.15 bridge / canonical bridge /
//                stablecoin wrapper (a wrapped asset has no token of its own to farm), 0.10 CEX
//   chainMult  = 1 + 0.01 x min(chains, 5)   (more chains = more surface to farm, capped)
//   implied    = max(1000, round(base x growthMult x ageMult x farmMult x chainMult))
//
// No protocol name is ever special-cased: the same function scores every row. The early radar
// scores every rankable protocol below the floor by implied value (not by TVL alone), so a
// small farmable protocol can outrank a huge wrapped asset.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

